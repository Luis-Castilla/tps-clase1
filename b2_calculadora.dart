void main() {

  // Declaración de variables con tipado explícito

  int a = 15;
  int b = 4;

  // Operaciones básicas

  int suma = a + b;
  int resta = a - b;
  int multiplicacion = a * b;
  double division = a / b; // retorna double
  int modulo = a % b;
  int divisionEntera = a ~/ b; // división entera en Dart

  // Impresión de resultados

  print("Suma: $suma");
  print("Resta: $resta");
  print("Multiplicación: $multiplicacion");
  print("División: $division");
  print("Módulo: $modulo");
  print("División entera: $divisionEntera");
  
}